"""Upload store and edit pipeline for the image editor.

A Panel uploads one image (content-sniffed, 25 MB cap) into a Brain-managed temp folder under a
random name. Edits run on that file through `ImageTools`; the result is written to the pictures
folder (`~/Pictures/Lupin` by default) and the uploaded original is deleted. Nothing here takes a
path from a client: file names are generated by the store.
"""

from __future__ import annotations

import asyncio
import contextlib
import logging
import re
import secrets
import shutil
import tempfile
import time
from collections import OrderedDict
from collections.abc import AsyncIterable, Callable
from datetime import datetime
from pathlib import Path
from typing import Any

from app.images.tools import OUTPUT_FORMATS, ImageTools, ToolError

logger = logging.getLogger(__name__)

MAX_UPLOAD_BYTES = 25 * 1024 * 1024
MAX_PENDING = 20
MAX_PIXELS = 50_000_000
MAX_CONCURRENT_INGESTS = 2
MAX_RESULTS = 50
MAX_OPS = 5
MAX_SIDE = 16384
STALE_SECONDS = 24 * 3600
TOPIC = "images"
ID_RE = re.compile(r"^[0-9a-f]{32}$")

_HEIC_BRANDS = {b"heic", b"heix", b"heim", b"heis", b"hevc", b"hevx", b"mif1", b"msf1", b"heif"}
MEDIA_TYPES = {
    "png": "image/png",
    "jpg": "image/jpeg",
    "gif": "image/gif",
    "webp": "image/webp",
    "heic": "image/heic",
}


class ImageError(Exception):
    """A request the editor refuses. `code` is machine-readable; `status` is the HTTP status."""

    def __init__(self, code: str, status: int = 422) -> None:
        super().__init__(code)
        self.code = code
        self.status = status


def sniff_format(head: bytes) -> str | None:
    """Image format from the first bytes (never from a name): png, jpg, gif, webp or heic."""
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    if head.startswith(b"\xff\xd8\xff"):
        return "jpg"
    if head.startswith((b"GIF87a", b"GIF89a")):
        return "gif"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "webp"
    if head[4:8] == b"ftyp" and head[8:12] in _HEIC_BRANDS:
        return "heic"
    return None


def parse_ops(raw: Any) -> list[dict[str, Any]]:
    """Validate and normalise an edit list. Raises ImageError('bad_request') on anything odd."""
    if not isinstance(raw, list) or not 1 <= len(raw) <= MAX_OPS:
        raise ImageError("bad_request")
    return [_parse_op(item) for item in raw]


def _int(value: Any, low: int, high: int) -> int:
    if type(value) is not int or not low <= value <= high:
        raise ImageError("bad_request")
    return value


def _fraction(value: Any) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ImageError("bad_request")
    number = float(value)
    if not 0.0 <= number <= 1.0:
        raise ImageError("bad_request")
    return number


def _parse_op(item: Any) -> dict[str, Any]:
    if not isinstance(item, dict):
        raise ImageError("bad_request")
    op = item.get("op")
    if op == "crop":
        x, y, w, h = (_fraction(item.get(key)) for key in ("x", "y", "w", "h"))
        if w <= 0 or h <= 0 or x + w > 1.0001 or y + h > 1.0001:
            raise ImageError("bad_request")
        return {"op": "crop", "x": x, "y": y, "w": w, "h": h}
    if op == "resize":
        width = item.get("width")
        height = item.get("height")
        if width is None and height is None:
            raise ImageError("bad_request")
        return {
            "op": "resize",
            "width": None if width is None else _int(width, 1, MAX_SIDE),
            "height": None if height is None else _int(height, 1, MAX_SIDE),
        }
    if op == "compress":
        quality = item.get("quality", 70)
        return {"op": "compress", "quality": _int(quality, 1, 100)}
    if op == "remove_background":
        return {"op": "remove_background"}
    if op == "convert":
        fmt = str(item.get("format") or "").lower()
        if fmt == "webp":
            raise ImageError("unavailable", 501)
        if fmt not in OUTPUT_FORMATS:
            raise ImageError("bad_request")
        return {"op": "convert", "format": "jpg" if fmt == "jpeg" else fmt}
    raise ImageError("bad_request")


class ImageService:
    """Holds pending uploads and finished results; runs edits one at a time."""

    def __init__(
        self,
        tools: ImageTools,
        *,
        store_dir: Path | None = None,
        pictures_dir: Path | None = None,
        clock: Callable[[], datetime] = datetime.now,
        max_bytes: int = MAX_UPLOAD_BYTES,
    ) -> None:
        self._tools = tools
        self._dir = Path(store_dir) if store_dir else Path(tempfile.gettempdir()) / "lupin-images"
        self._pictures = Path(pictures_dir) if pictures_dir else Path.home() / "Pictures" / "Lupin"
        self._clock = clock
        self._max_bytes = max_bytes
        self._pending: OrderedDict[str, dict[str, Any]] = OrderedDict()
        self._results: OrderedDict[str, dict[str, Any]] = OrderedDict()
        self._lock = asyncio.Lock()
        self._ingests = asyncio.Semaphore(MAX_CONCURRENT_INGESTS)
        self._dir.mkdir(parents=True, exist_ok=True)
        with contextlib.suppress(OSError):
            self._dir.chmod(0o700)
        self._purge(everything=True)

    # ---------------------------------------------------------------- housekeeping

    def _purge(self, everything: bool = False) -> None:
        """Delete leftover store files (all of them at startup, stale ones later)."""
        cutoff = time.time() - STALE_SECONDS
        live = {entry["path"] for entry in self._pending.values()}
        try:
            entries = list(self._dir.iterdir())
        except OSError:
            return
        for path in entries:
            if not path.is_file() or path in live:
                continue
            with contextlib.suppress(OSError):
                if everything or path.stat().st_mtime < cutoff:
                    path.unlink()

    def _forget(self, image_id: str) -> None:
        entry = self._pending.pop(image_id, None)
        if entry is None:
            return
        for path in (entry["path"], self._preview_path(image_id)):
            with contextlib.suppress(OSError):
                path.unlink()

    def _preview_path(self, image_id: str) -> Path:
        return self._dir / f"{image_id}.preview.jpg"

    # ---------------------------------------------------------------- uploads

    async def ingest(self, chunks: AsyncIterable[bytes]) -> dict[str, Any]:
        """Store an uploaded body as a new pending image. Refuses non-images and oversize."""
        async with self._ingests:
            return await self._ingest(chunks)

    async def _ingest(self, chunks: AsyncIterable[bytes]) -> dict[str, Any]:
        self._purge()
        while len(self._pending) >= MAX_PENDING:  # make room before writing anything
            self._forget(next(iter(self._pending)))
        image_id = secrets.token_hex(16)
        part = self._dir / f"{image_id}.part"
        head = b""
        size = 0
        try:
            with part.open("wb") as handle:
                async for chunk in chunks:
                    size += len(chunk)
                    if size > self._max_bytes:
                        raise ImageError("too_large", 413)
                    if len(head) < 32:
                        head = (head + chunk)[:32]
                    handle.write(chunk)
            fmt = sniff_format(head)
            if size == 0 or fmt is None:
                raise ImageError("not_image", 415)
            final = self._dir / f"{image_id}.{fmt}"
            part.rename(final)
        except BaseException:
            with contextlib.suppress(OSError):
                part.unlink()
            raise
        try:
            final, dims = await asyncio.to_thread(self._prepare, image_id, final)
        except BaseException:
            for path in (final, self._dir / f"{image_id}.upright"):
                with contextlib.suppress(OSError):
                    path.unlink()
            raise
        info = {"id": image_id, "format": fmt, "size": final.stat().st_size, "path": final}
        info["width"], info["height"] = dims
        self._pending[image_id] = info
        return self.describe(info)

    def _prepare(self, image_id: str, path: Path) -> tuple[Path, tuple[int, int]]:
        """Check the pixel size, then bake any EXIF rotation into the stored file."""
        dims = self._tools.dimensions(path)
        if dims is None:
            raise ImageError("not_image", 415)
        if dims[0] * dims[1] > MAX_PIXELS:
            raise ImageError("too_large", 413)
        upright = self._dir / f"{image_id}.upright"
        if self._tools.normalize_orientation(path, upright):
            with contextlib.suppress(OSError):
                path.unlink()
            upright.rename(path)
            dims = self._tools.dimensions(path) or dims
        return path, dims

    @staticmethod
    def describe(entry: dict[str, Any]) -> dict[str, Any]:
        return {key: entry[key] for key in ("id", "format", "size", "width", "height") if key in entry}

    def warm_up(self) -> None:
        self._tools.warm_up()

    def last_pending(self) -> dict[str, Any] | None:
        if not self._pending:
            return None
        return self.describe(next(reversed(self._pending.values())))

    def pending_path(self, image_id: str) -> tuple[Path, str] | None:
        entry = self._pending.get(image_id) if ID_RE.fullmatch(image_id or "") else None
        if entry is None or not entry["path"].is_file():
            return None
        return entry["path"], entry["format"]

    async def preview(self, image_id: str) -> tuple[Path, str] | None:
        """A file the browser can show: the original, or a JPEG copy for HEIC."""
        found = self.pending_path(image_id)
        if found is None:
            return None
        path, fmt = found
        if fmt != "heic":
            return path, MEDIA_TYPES[fmt]
        preview = self._preview_path(image_id)
        if not preview.is_file():
            try:
                await asyncio.to_thread(self._tools.convert, path, preview, "jpg", 80)
            except ToolError:
                return None
        return preview, MEDIA_TYPES["jpg"]

    def discard(self, image_id: str) -> bool:
        if not ID_RE.fullmatch(image_id or "") or image_id not in self._pending:
            return False
        self._forget(image_id)
        return True

    # ---------------------------------------------------------------- edits

    async def edit(self, image_id: str | None, raw_ops: Any) -> dict[str, Any]:
        """Apply the edits in order, save the result, delete the original."""
        ops = parse_ops(raw_ops)
        async with self._lock:
            if image_id is None:
                last = self.last_pending()
                image_id = last["id"] if last else None
            found = self.pending_path(image_id or "")
            if found is None:
                raise ImageError("unknown_image", 404)
            try:
                result = await asyncio.to_thread(self._run_ops, image_id, found[0], found[1], ops)
            except ToolError as exc:
                raise ImageError(exc.code, 501 if exc.code == "unavailable" else 422) from exc
            self._forget(image_id)
            self._results[result["id"]] = result
            while len(self._results) > MAX_RESULTS:
                self._results.popitem(last=False)
            return self._public(result)

    def _run_ops(self, image_id: str, src: Path, fmt: str, ops: list[dict[str, Any]]) -> dict[str, Any]:
        current, current_fmt = src, fmt
        temps: list[Path] = []
        try:
            for index, op in enumerate(ops):
                kind = op["op"]
                out_fmt = "png" if current_fmt == "webp" else current_fmt  # sips cannot write WebP
                if kind == "convert":
                    out_fmt = op["format"]
                elif kind == "compress":
                    out_fmt = "jpg"
                elif kind == "remove_background":
                    out_fmt = "png"
                out = self._dir / f"{image_id}.step{index}.{OUTPUT_FORMATS.get(out_fmt, (None, out_fmt))[1]}"
                temps.append(out)
                self._apply(kind, op, current, out, out_fmt)
                current, current_fmt = out, out_fmt
            if current_fmt in OUTPUT_FORMATS:  # every saved format can carry GPS (PNG via eXIf/XMP)
                clean = self._dir / f"{image_id}.clean.{OUTPUT_FORMATS[current_fmt][1]}"
                temps.append(clean)
                self._tools.strip_gps(current, clean)
                current = clean
            self._pictures.mkdir(parents=True, exist_ok=True)
            stamp = self._clock().strftime("%Y%m%d-%H%M%S")
            ext = OUTPUT_FORMATS.get(current_fmt, (None, current_fmt))[1]
            name = f"lupin-{stamp}-{secrets.token_hex(2)}.{ext}"
            destination = self._pictures / name
            shutil.move(str(current), str(destination))
            return {"id": secrets.token_hex(16), "name": name, "format": current_fmt, "path": destination}
        except OSError as exc:
            raise ToolError("edit_failed") from exc
        finally:
            for path in temps:
                with contextlib.suppress(OSError):
                    path.unlink()

    def _apply(self, kind: str, op: dict[str, Any], src: Path, dst: Path, out_fmt: str) -> None:
        tools = self._tools
        if kind == "crop":
            dims = tools.dimensions(src)
            if dims is None:
                raise ToolError("edit_failed")
            width, height = dims
            if width * height > MAX_PIXELS:
                raise ToolError("too_large")
            left = min(int(op["x"] * width), width - 1)
            top = min(int(op["y"] * height), height - 1)
            crop_w = max(1, min(int(round(op["w"] * width)), width - left))
            crop_h = max(1, min(int(round(op["h"] * height)), height - top))
            tools.crop(src, dst, left, top, crop_w, crop_h)
        elif kind == "resize":
            self._check_resize_target(src, op["width"], op["height"])
            tools.resize(src, dst, op["width"], op["height"])
        elif kind == "compress":
            tools.convert(src, dst, "jpg", op["quality"])
        elif kind == "convert":
            tools.convert(src, dst, op["format"])
        elif kind == "remove_background":
            tools.remove_background(src, dst)
        else:
            raise ToolError("edit_failed")

    def _check_resize_target(self, src: Path, width: int | None, height: int | None) -> None:
        """Refuse a resize whose output would exceed the pixel limit."""
        dims = self._tools.dimensions(src)
        if dims is None:
            raise ToolError("edit_failed")
        if width and height:
            out_w, out_h = width, height
        elif width:
            out_w, out_h = width, dims[1] * width / dims[0]
        else:
            out_w, out_h = dims[0] * height / dims[1], height
        if out_w * out_h > MAX_PIXELS:
            raise ToolError("too_large")

    # ---------------------------------------------------------------- results

    @staticmethod
    def _public(result: dict[str, Any]) -> dict[str, Any]:
        return {key: result[key] for key in ("id", "name", "format")}

    def result_file(self, result_id: str) -> tuple[Path, str, str] | None:
        entry = self._results.get(result_id) if ID_RE.fullmatch(result_id or "") else None
        if entry is None or not entry["path"].is_file():
            return None
        return entry["path"], entry["name"], MEDIA_TYPES.get(entry["format"], "application/octet-stream")
